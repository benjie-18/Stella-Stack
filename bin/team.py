#!/usr/bin/env python3
"""The build team as a preset (F2b item G; spec B4), stdlib only. The preset (a key of the role-assignments data's effort_modes) holds
`agents`: per agent its description, tools, link, fallbacks and escalation_chain. The agent's instructions are tracked prose in the
folder of the index key team_bodies (<agent>.md); the agent files live in the folder of the index key agents_dir. No agent, model or
folder name is in this file.
  team.py generate [--preset ID] [--out DIR] [--json]   writes DIR/<agent>.md for every agent of the preset (front matter name,
      description, model, effort, tools; a generated marker line with the preset and a digest of its inputs; the body) and nothing
      else; one trusted `team.generated` event line. DIR defaults to the folder of agents_dir. An unknown preset writes nothing.
  team.py check [--preset ID] [--sessions DIR] [--json]  one result per agent; exit 0 only when all agree: (1) the file equals what
      generate would write (a hand edit fails, naming the field or "body"); (2) the models the agent's transcripts in the latest
      session ran on are its link's, a fallback's or a rung's (else the agent, the model and the count are named); an agent with no
      transcript is "not seen", no failure; (3) a file with the marker whose agent the preset no longer has is stale (fails); a file
      without the marker is listed as unmanaged, and fails when its front matter name is a preset agent's. A failing check writes one alert
      line. Output is always JSON; a sessions folder that is missing or unreadable is a `warnings` entry (and a stderr line), no failure.
  The preset is read through stella_data.served (data `check` refuses is never used); generate never writes through a symbolic link.
  Latest session = the newest top-level *.jsonl of DIR (--sessions; default: HOME/.claude/projects/<this root with every
  non-alphanumeric turned into a dash>); its transcripts are DIR/<session>/subagents/agent-*.jsonl, matched to an agent by the
  agentType of the agent-*.meta.json beside each.
Exit: 0 ok; 1 refused or failed (catalog code and plain message on stderr, JSON on stdout)."""
import os, sys

if __name__ == "__main__" and not sys.flags.isolated:   # run directly: PYTHONPATH and the current folder must not decide what is imported
    try:
        os.execv(sys.executable, [sys.executable, "-I", *sys.argv])
    except OSError:
        sys.exit("STL-CFG-310 team.py could not restart itself isolated (python3 -I); nothing was written")

import argparse, collections, hashlib, json, re

BIN = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, BIN)   # python3 -I does not add the script folder
import event_log as el
import stella_data as sd

REFUSED, DIFFERS, SESSION, UNEXPECTED = "STL-MDL-743", "STL-MDL-744", "STL-MDL-745", "STL-CFG-310"
MARK = "<!-- generated by team.py from preset "   # a file that holds this line is managed
FIELDS = ("name", "description", "model", "effort", "tools")

class Stop(Exception):
    def __init__(self, code, problem):
        super().__init__(problem)
        self.code, self.problem = code, problem

def preset_agents(name):
    """{agent: entry} of the preset `name`; Stop (REFUSED) when the preset is unknown or has no agents."""
    row = next((r for r in sd.rows() if r["schema"] == "role-assignments" and r["format"] == "json"), None)
    docs = [d for _, d in sd.served([row["id"]])["_rows"][row["id"]][0]] if row else []   # served: data `check` refuses is never used
    mode = (docs[0]["effort_modes"] if docs else {}).get(name)
    if not mode or not mode.get("agents"):
        raise Stop(REFUSED, f"preset {sd.idn(name)} is not a preset with agents")
    return mode["agents"]

def folders(out=None):
    idx = sd.load(sd.INDEX)
    return os.path.join(sd.ROOT, out) if out else sd.safe(idx["agents_dir"]), sd.safe(idx["team_bodies"])   # an index path stays inside the root, links followed

def render(preset, name, e, bodies):
    """The file generate writes for one agent, as text."""
    try:
        with open(os.path.join(bodies, name + ".md"), encoding="utf-8") as f:
            body = f.read()
    except OSError:
        raise Stop(REFUSED, f"agent {sd.idn(name)} has no body text in the team_bodies folder") from None
    digest = hashlib.sha256(json.dumps([name, e, body], sort_keys=True).encode()).hexdigest()[:12]
    head = [("name", name), ("description", e["description"]), ("model", e["link"]["model"]),
            ("effort", e["link"]["parameters"].get("effort", "")), ("tools", ", ".join(e["tools"]))]
    return "---\n" + "".join(f"{k}: {v}\n" for k, v in head if v != "") + f"---\n\n{MARK}{preset} (inputs {digest}); edit the preset and the body file, not this file -->\n\n{body}"

def split(text):
    """(front matter {key: value}, the rest) of a file."""
    m = re.match(r"---\n(.*?)\n---\n(.*)\Z", text, re.S)
    if not m:
        return {}, text
    return dict(l.split(": ", 1) for l in m.group(1).split("\n") if ": " in l), m.group(2)

def cmd_generate(a):
    ag = preset_agents(a.preset)
    out, bodies = folders(a.out)
    files = {n: render(a.preset, n, e, bodies) for n, e in ag.items()}   # all rendered before anything is written
    links = [n for n in files if os.path.islink(os.path.join(out, n + ".md"))]
    if links:   # all or none: nothing is written when one agent file is a link
        raise Stop(REFUSED, f"agent file {sd.idn(links[0])} is a symbolic link; generate never writes through one")
    el.preflight()
    os.makedirs(out, exist_ok=True)
    for n, t in files.items():
        try:
            fd = os.open(os.path.join(out, n + ".md"), os.O_WRONLY | os.O_CREAT | os.O_TRUNC | os.O_NOFOLLOW, 0o644)   # never through a link
        except OSError:
            raise Stop(REFUSED, f"agent file {sd.idn(n)} cannot be written (not a plain file)") from None
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(t)
    el.append(el.build("team.generated", f"agent files of preset {a.preset}", new={"preset": a.preset, "agents": sorted(files)}))
    print(json.dumps({"preset": a.preset, "written": sorted(files)}))
    return 0

def latest_models(sessions):
    """({agentType: Counter of logged models}, the latest session's name or None, a warning or None) of the newest top-level session file."""
    try:
        tops = [e for e in os.scandir(sessions) if e.is_file() and e.name.endswith(".jsonl")]
    except OSError:
        return {}, None, "the sessions folder is missing or unreadable, so no agent could be matched to a session (every agent reads not seen)"
    if not tops:
        return {}, None, None
    top = max(tops, key=lambda e: e.stat().st_mtime)
    sub, got = os.path.join(sessions, top.name[:-6], "subagents"), collections.defaultdict(collections.Counter)
    for t in sorted(os.listdir(sub)) if os.path.isdir(sub) else []:
        if not (t.startswith("agent-") and t.endswith(".jsonl")):
            continue
        try:
            with open(os.path.join(sub, t[:-6] + ".meta.json"), encoding="utf-8") as f:
                kind = json.load(f)["agentType"]
            with open(os.path.join(sub, t), encoding="utf-8", errors="replace") as f:
                for line in f:
                    try:
                        m = json.loads(line)["message"]["model"]
                    except (ValueError, KeyError, TypeError):
                        continue
                    if isinstance(m, str) and not m.startswith("<"):   # "<synthetic>" marks a line no model wrote
                        got[kind][m] += 1
        except (OSError, ValueError, KeyError, TypeError):
            continue   # a transcript with no readable meta belongs to no agent
    return got, top.name, None

def agrees(logged, e):
    """Whether a logged model id is the agent's link, a fallback or a rung: a catalog model id is a whole dash-separated token of it.
    shortcut: a catalog id with a dash of its own is not matched as one token; upgrade when the team uses such a model."""
    ids = {l["model"] for l in [e["link"], *e.get("fallbacks", []), *e.get("escalation_chain", [])]}
    return any(i in re.split(r"-", logged) for i in ids)

def cmd_check(a):
    ag = preset_agents(a.preset)
    out, bodies = folders()
    # shortcut: the default sessions folder is Claude Code's layout for this root, guessed from the path; upgrade when it moves or an install names it in data
    sess = a.sessions or os.path.join(os.path.expanduser("~"), ".claude", "projects", re.sub(r"[^A-Za-z0-9]", "-", sd.ROOT))
    models, latest, warn = latest_models(sess)
    res, bad = [], []
    for n, e in ag.items():
        want, probs = render(a.preset, n, e, bodies), []
        try:
            with open(os.path.join(out, n + ".md"), encoding="utf-8") as f:
                have = f.read()
        except OSError:
            have = None
            probs.append({"code": DIFFERS, "problem": f"agent {n}: its file is missing"})
        if have is not None and have != want:
            (hf, hr), (wf, wr) = split(have), split(want)
            what = [k for k in dict.fromkeys([*FIELDS, *hf, *wf]) if hf.get(k) != wf.get(k)] + (["body"] if hr != wr else [])
            probs.append({"code": DIFFERS, "problem": f"agent {n}: its file differs from the preset in {', '.join(what) or 'its marker'}"})
        seen = models.get(n)
        for m, c in sorted((seen or {}).items()):
            if not agrees(m, e):
                probs.append({"code": SESSION, "problem": f"agent {n}: ran on model {sd.idn(m)} ({c} lines) in the latest session, which is not its link, a fallback or a rung"})
        res.append({"agent": n, "ok": not probs, "session": dict(seen) if seen else "not seen", "problems": probs})
        bad += probs
    stale, unmanaged = [], []
    for f in sorted(os.listdir(out)) if os.path.isdir(out) else []:
        if f.endswith(".md") and f[:-3] not in ag:
            with open(os.path.join(out, f), encoding="utf-8", errors="replace") as fh:
                text = fh.read()
            (stale if MARK in text else unmanaged).append(f[:-3])
            twin = split(text)[0].get("name", "").strip("\"' ")   # Claude Code keys agents by name, not by file name
            if twin in ag:
                bad.append({"code": DIFFERS, "problem": f"file {sd.idn(f[:-3])} declares the name of preset agent {sd.idn(twin)} and is not that agent's generated file"})
    bad += [{"code": DIFFERS, "problem": f"agent {n}: its file is stale (generated, but the preset has no such agent)"} for n in stale]
    doc = {"preset": a.preset, "ok": not bad, "latest_session": latest, "agents": res, "stale": stale, "unmanaged": unmanaged, "warnings": [warn] if warn else []}
    print(json.dumps(doc))
    if warn:
        print("warning: " + warn, file=sys.stderr)
    if bad:
        b = bad[0]
        el.say(b["code"], "; ".join(x["problem"] for x in bad[:3]) + (f" (and {len(bad) - 3} more)" if len(bad) > 3 else ""), alert=True)
    return 1 if bad else 0

def main(argv):
    ap = argparse.ArgumentParser(prog="team.py", description="The build team preset: generate agent files and check them.")
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("generate", "check"):
        p = sub.add_parser(name)
        p.add_argument("--preset", default=None)
        p.add_argument("--json", action="store_true")
    sub.choices["generate"].add_argument("--out")
    sub.choices["check"].add_argument("--sessions")
    a = ap.parse_args(argv)
    try:
        a.preset = a.preset or sd.load(sd.INDEX)["team_preset"]
        return {"generate": cmd_generate, "check": cmd_check}[a.cmd](a)
    except Stop as x:
        s = x
    except sd.DataError as e:
        s = Stop(getattr(e, "code", UNEXPECTED), str(e)[:180])
    except Exception as e:   # never a traceback, never the error's text: the type only
        s = Stop(UNEXPECTED, f"{type(e).__name__}, an unexpected failure of team.py {a.cmd}")
    print(json.dumps({"code": s.code, "problem": el.scrub(s.problem)}))
    el.say(s.code, s.problem, alert=True)
    return 1

if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
